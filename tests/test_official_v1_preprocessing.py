@pytest.fixture(scope="module")
def processor():
    if not RAW_PATH.exists() or not REFERENCE_PATH.exists():
        pytest.skip("official parity fixtures are unavailable")
    return NeuroSelectOfficialV1EventPreprocessing.from_raw(
        RAW_PATH,
        recording_start_seconds=308.0,
    )


def test_official_v1_matches_validated_trial_two_reference(processor):
    reference = np.load(REFERENCE_PATH)["official"]
    assert processor.signal.shape[1] == CHANNEL_COUNT
    assert tuple(processor.channel_names) == tuple(
        json.loads(Path(ROOT / "results/official_event_tensor_parity.json").read_text())[
            "channel_order"
        ]["official_extractor_header"]
    )
    for index, (timestamp, _label) in enumerate(EVENTS):
        result = processor.extract_event(timestamp)
        assert result.event_time_seconds == timestamp
        assert result.tensor.shape == (25, CHANNEL_COUNT)
        assert result.tensor.dtype == np.float32
        assert np.isfinite(result.tensor).all()
        np.testing.assert_allclose(result.tensor, reference[index], rtol=0.0, atol=1e-20)


def test_first_event_has_continuous_context_without_padding(processor):
    result = processor.extract_event(EVENTS[0][0])
    assert result.metadata["event_sample_index"] == 3764
    assert result.metadata["window_start_sample_index"] == 3754
