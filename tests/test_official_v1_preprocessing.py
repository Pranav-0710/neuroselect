@pytest.mark.parametrize(
    "trial_number,event_index,timestamp,expected_hash,expected_window_start",
    [
        (3, 9, 396.790, "c5226ffaec2a57d581f8baeca6360f4a6659bb494989f3afb0db91ec38cc8814", 4430),
        (5, 10, 420.270, "3ff43a97570571281c9db47c6a368bf852542e077f13fa01d7b84495ea240921", 5604),
        (6, 2, 430.050, "b7c73309f3b78d1fe468bd13d1861ae9192032ef0a607a182a077c09292d04b7", 6093),
        (7, 19, 444.870, "3449e4a9196b0fdcaaca5bbf7646a6fe2cf8445ec94900ef95b18b0363ff8af5", 6834),
    ],
)
def test_four_overlap_regressions_match_independent_official_hashes(
    processor, trial_number, event_index, timestamp, expected_hash, expected_window_start
):
    """The four forensic references were generated by the pinned official extractor."""
    if not PARITY_PATH.exists():
        pytest.skip("eight-trial official parity reference is unavailable")
    parity = json.loads(PARITY_PATH.read_text(encoding="utf-8"))
    trial = next(row for row in parity["trial_identity_and_event_audit"] if row["trial_number"] == trial_number)
    reference = next(row for row in trial["events"] if row["event_index"] == event_index)
    assert reference["official_tensor"]["sha256"] == expected_hash
    result = processor.extract_event(timestamp)
    assert result.tensor.shape == (25, CHANNEL_COUNT)
    assert np.isfinite(result.tensor).all()
    assert result.metadata["window_start_sample_index"] == expected_window_start
    import hashlib

    assert hashlib.sha256(np.ascontiguousarray(result.tensor.T).tobytes()).hexdigest() == expected_hash


