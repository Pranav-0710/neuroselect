ROOT = Path(__file__).resolve().parents[1]
RAW_PATH = ROOT / "data/raw/spanishbcbl_s22/MEG/FIF/22_9788/231214/block1.fif"
REFERENCE_PATH = ROOT / "results/official_event_tensor_examples/trial_2_first_5.npz"
